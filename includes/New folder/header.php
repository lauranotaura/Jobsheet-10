<?php
// Mencegah error jika session sudah dimulai sebelumnya oleh auth.php
if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

// Cek status login pengguna
$sudahLogin = isset($_SESSION['user_id']);

// Menghitung path dasar ($base) secara otomatis berdasarkan kedalaman folder
$current_dir = dirname($_SERVER['SCRIPT_NAME']);
$depth = substr_count(trim($current_dir, '/'), '/');
$base = str_repeat('../', max(0, $depth));
?>
<!DOCTYPE html>
<html lang="id">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title><?php echo $page_title ?? 'SIMPUS-Mini'; ?></title>
    <link rel="stylesheet" href="<?php echo $base; ?>assets/style.css">
</head>
<body>
    <header>
        <h1>SIMPUS-Mini</h1>
        <button type="button" id="nav-toggle-btn" class="nav-toggle-label" aria-label="Menu">&#9776;</button>
        <nav>
            <ul>
                <li><a href="<?php echo $base; ?>index.php">Beranda</a></li>
                <li><a href="<?php echo $base; ?>buku/list.php">Daftar Buku</a></li>
                <?php if ($sudahLogin): ?>
                    <li><a href="<?php echo $base; ?>buku/tambah.php">Tambah Buku</a></li>
                    <li><a href="<?php echo $base; ?>anggota/list.php">Daftar Anggota</a></li>
                    <li><a href="<?php echo $base; ?>anggota/tambah.php">Tambah Anggota</a></li>
                <?php endif; ?>
            </ul>
        </nav>
        <div class="auth-status">
            <?php if ($sudahLogin): ?>
                <span><?php echo htmlspecialchars($_SESSION['nama']); ?></span>
                <a href="<?php echo $base; ?>auth/logout.php">Logout</a>
            <?php else: ?>
                <a href="<?php echo $base; ?>auth/login.php">Login</a>
            <?php endif; ?>
        </div>
    </header>
    <main class="container">